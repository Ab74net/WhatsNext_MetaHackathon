"""Build metadata-free homepage WebPs from the five developer-selected photos.

Run from the repository root: apps/api/.venv/Scripts/python scripts/prepare_intro_photos.py
The raw source directory stays git-ignored; only optimized public assets are shipped.
"""
import hashlib
import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts" / "photostoplayfirst"
TARGET = ROOT / "apps" / "web" / "public" / "hero"
DETAILS = {
    "1.jpg": ("Wildfire", "Orange wildfire smoke rising above trees and a hillside at night."),
    "2.jpg": ("Wildfire recovery", "The remaining walls and chimney of a fire-damaged home at sunset."),
    "3.png": ("Flood", "A wooden house leaning into floodwater beside a grassy riverbank."),
    "4.jpg": ("Storm recovery", "An opened home with a missing roof, exposed framing, and damaged belongings."),
    "5.png": ("House fire", "Fire and smoke rising from a house, viewed from across the street."),
}


def natural_key(path):
    return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", path.name)]


def prepare():
    TARGET.mkdir(parents=True, exist_ok=True)
    manifest, seen = [], set()
    for file in sorted((p for p in SOURCE.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}), key=natural_key):
        image = ImageOps.exif_transpose(Image.open(file)).convert("RGB")
        digest = hashlib.sha256(str(image.size).encode() + image.tobytes()).hexdigest()
        if digest in seen:
            continue
        seen.add(digest)
        # Keep the house and damage while excluding the foreground people in these two sources.
        if file.name == "3.png":
            image = image.crop((320, 0, image.width, image.height))
        elif file.name == "4.jpg":
            image = image.crop((2200, 0, image.width, image.height))
        name = f"intro-{len(manifest) + 1}"
        widths = [w for w in [768, 1280, 1920] if w <= image.width]
        if image.width < 1920 and image.width not in widths:
            widths.append(image.width)
        for width in widths:
            size = (width, round(image.height * width / image.width))
            # New pixels carry no EXIF, GPS, XMP, comments, or embedded source metadata.
            clean = Image.frombytes("RGB", size, image.resize(size, Image.Resampling.LANCZOS).tobytes())
            clean.save(TARGET / f"{name}-{width}.webp", "WEBP", quality=84, method=6)
        hazard, alt = DETAILS[file.name]
        manifest.append({"sourceFile": file.name, "name": name, "hazard": hazard, "alt": alt,
                         "widths": widths, "width": image.width, "height": image.height})
    (TARGET / "intro-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (ROOT / "apps/web/src/lib/introPhotos.ts").write_text(
        "// Generated by scripts/prepare_intro_photos.py; source order is natural filename order.\n"
        + "export const INTRO_PHOTOS = " + json.dumps(manifest, indent=2) + ";\n", encoding="utf-8")
    print("Homepage introduction order:", " → ".join(p["sourceFile"] for p in manifest))


if __name__ == "__main__":
    prepare()
